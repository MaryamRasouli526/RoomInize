package se.gritacademy.roominize.model;

/**
 * RoomType är en enum som definierar vilka typer av rum som finns i systemet.
 * Den används för att kategorisera rum, till exempel sovrum eller vardagsrum,
 * vilket gör det enklare att hantera logik och filtrering i applikationen.
 */
public enum RoomType {

    /**
     * Representerar ett sovrum.
     */
    BEDROOM,

    /**
     * Representerar ett vardagsrum.
     */
    LIVING_ROOM
}
